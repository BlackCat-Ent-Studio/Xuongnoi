import { openBrowser, openSample, sleep, URL, SCRATCH } from './common.mjs';
const OUT = `${SCRATCH}/humanoid`;
const { browser, page, logs } = await openBrowser();
try {
  await page.goto(URL, { waitUntil: 'load' });
  await page.waitForSelector('.topbar', { timeout: 15000 });
  await sleep(500);
  if (await page.locator('[data-tut="invite-no"]').isVisible()) await page.locator('[data-tut="invite-no"]').click();
  await sleep(300);
  await openSample(page, 'side-stars');
  await sleep(600);
  await page.screenshot({ path: `${OUT}/1-side-idle.png` });
  await page.locator('#btn-play').click();
  await sleep(900);
  await page.mouse.move(1000,400); await page.mouse.wheel(0,-2500); await sleep(500);
  await page.keyboard.down('ArrowRight');
  await sleep(450);
  await page.screenshot({ path: `${OUT}/2-side-walk-right.png` });
  await sleep(130);
  await page.screenshot({ path: `${OUT}/2b-side-walk-right.png` });
  await page.keyboard.up('ArrowRight');
  await page.keyboard.down('ArrowLeft');
  await sleep(500);
  await page.screenshot({ path: `${OUT}/3-side-walk-left.png` });
  await page.keyboard.up('ArrowLeft');
  await sleep(600);
  await page.screenshot({ path: `${OUT}/4-side-idle-after.png` });
  await page.keyboard.down('Space');
  await sleep(250);
  await page.screenshot({ path: `${OUT}/5-side-air.png` });
  await page.keyboard.up('Space');
  await sleep(1200);
  await openSample(page, '3d-hop');
  await sleep(600);
  await page.screenshot({ path: `${OUT}/6-3d-idle.png` });
  await page.locator('#btn-play').click();
  await sleep(900);
  await page.mouse.move(1000,400); await page.mouse.wheel(0,-900); await sleep(500);
  await page.keyboard.down('ArrowUp');
  await sleep(500);
  await page.screenshot({ path: `${OUT}/7-3d-walk.png` });
  await page.keyboard.down('Space');
  await sleep(250);
  await page.screenshot({ path: `${OUT}/8-3d-air.png` });
  console.log('logs', JSON.stringify(logs).slice(0, 800));
} catch (e) { console.log('ERR', e); } finally { await browser.close(); }
